end

function M.TransformList(list)
    if type(list) ~= "table" then return list end
    local out = {}
    for i, pt in ipairs(list) do
        if type(pt) == "table" and type(pt[1]) == "number" and type(pt[2]) == "number" then
            local x, y = M.Transform(pt[1], pt[2])
            out[i] = { x, y }
        else
            out[i] = pt
        end
    end
    return out
end

